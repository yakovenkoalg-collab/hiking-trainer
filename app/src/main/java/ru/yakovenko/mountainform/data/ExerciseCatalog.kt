fun ExerciseStep.catalogId(): String = exerciseId.ifBlank {
    when (id) {
        "warmup", "walk-warmup", "walk-cooldown", "cooldown" -> "walk"
        else -> id
    }
}

fun ExerciseStep.imageKey(): String = illustrationKey.ifBlank { catalogId() }
