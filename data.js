function getExForVenue(ex, venue) {
  if (venue === 'gym') return ex;
  for (const [rx, homeSub, outdoorSub] of VENUE_SUBS) {
    if (rx.test(ex.name)) {
      const s = venue === 'home' ? homeSub : outdoorSub;
      if (!s) return ex;
      let params = s.p ? s.p(ex.params) : ex.params;
      return { name: s.n, params: params, notes: ex.notes };
    }
  }
  return ex;
}

function dayVenueKey(w, d) { return `w${w}d${d}`; }
function getProfileVenue(w, d) {
  const p = PROFILES.find(p => p.id === state.profile);
  return p ? p.venue(w, d) : 'gym';
}
function getDayVenue(w, d) { return state.venues[dayVenueKey(w, d)] || getProfileVenue(w, d); }
function isDayOverridden(w, d) { return !!state.venues[dayVenueKey(w, d)]; }
function setDayVenue(w, d, v) {
  const profileDefault = getProfileVenue(w, d);
  if (v === profileDefault) delete state.venues[dayVenueKey(w, d)];
  else state.venues[dayVenueKey(w, d)] = v;
  saveState();
  render();
}
function setProfile(id) {
  state.profile = id;
  state.venues = {}; // reset per-day overrides
  saveState();
  render();
}

